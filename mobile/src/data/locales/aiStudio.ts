export function withAiStudioTranslation<T extends { tabs: Strings }>(base: T, language: LanguageOption | null): T {
  const extra = language ? aiStudioTranslations[language] : undefined;
  if (!extra) {
    return base;
  }
  return { ...base, ...extra.studio, tabs: { ...base.tabs, ...extra.tabs } } as T;
}

export function withAiToolsUiTranslation<T extends object>(base: T, language: LanguageOption | null): T {
  const extra = language ? aiStudioTranslations[language] : undefined;
  return extra ? ({ ...base, ...extra.ui } as T) : base;
}
